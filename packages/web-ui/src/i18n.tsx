const dictionaries: Record<UiLanguage, Record<UiTextKey, string>> = {
  "zh-CN": zhCN,
  "en-US": enUS,
};

export type Translate = (
  key: UiTextKey,
  values?: Readonly<Record<string, string | number>>,
) => string;

export function translate(
  language: UiLanguage,
  key: UiTextKey,
  values: Readonly<Record<string, string | number>> = {},
): string {
  return dictionaries[language][key].replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name: string) =>
    Object.hasOwn(values, name) ? String(values[name]) : match,
  );
}

function initialLanguage(): UiLanguage {
  if (typeof window === "undefined") return "zh-CN";
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === "zh-CN" || stored === "en-US") return stored;
  } catch {
    // Browser privacy settings may disable localStorage. Language switching
    // remains available for the lifetime of the current page.
  }
  return window.navigator.language.toLowerCase().startsWith("zh") ? "zh-CN" : "en-US";
}

type I18nValue = Readonly<{
  language: UiLanguage;
  setLanguage: (language: UiLanguage) => void;
  t: Translate;
}>;

const I18nContext = createContext<I18nValue>({
  language: "zh-CN",
  setLanguage: () => undefined,
  t: (key, values) => translate("zh-CN", key, values),
});

export function I18nProvider({
  children,
  initialLanguage: configuredLanguage,
}: {
  children: ReactNode;
  initialLanguage?: UiLanguage;
}) {
  const [language, setLanguage] = useState<UiLanguage>(
    () => configuredLanguage ?? initialLanguage(),
  );
  const languageRef = useRef(language);
  languageRef.current = language;
  const t = useCallback<Translate>(
    (key, values) => translate(languageRef.current, key, values),
    [],
  );

  useEffect(() => {
    try {
      window.localStorage.setItem(STORAGE_KEY, language);
    } catch {
      // Keep the in-memory preference when persistent browser storage is unavailable.
    }
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo<I18nValue>(
    () => ({
      language,
      setLanguage,
      t,
    }),
    [language, t],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}

export function LanguageSelect() {
  const { language, setLanguage, t } = useI18n();
  return (
    <select
      aria-label={t("language.label")}
      className="product-language-select"
      onChange={(event) => setLanguage(event.target.value as UiLanguage)}
      value={language}
    >
      <option value="zh-CN">{t("language.zh")}</option>
      <option value="en-US">{t("language.en")}</option>
    </select>
  );
}
